import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import test, { after } from "node:test";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import { collectChangedTestContracts, collectTestSuiteInventory, evaluateFlowCoverageEvidence } from "../dist/test-evidence.js";
import { buildRepositoryEvidenceIndex } from "../dist/repository-index.js";
import { generateE2ePlan } from "../dist/e2e.js";

const exec = promisify(execFile);
const cli = fileURLToPath(new URL("../dist/cli.js", import.meta.url));
const roots = [];
after(async () => {
  for (const root of roots) await fs.rm(root, { recursive: true, force: true });
});

async function fixture(files) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "qamap-canonical-test-paths-"));
  roots.push(root);
  for (const [name, contents] of Object.entries(files)) {
    await fs.mkdir(path.dirname(path.join(root, name)), { recursive: true });
    await fs.writeFile(path.join(root, name), contents);
  }
  return root;
}

test("canonical JavaScript test filenames retain suite evidence without executing their imports", async () => {
  const root = await fixture({
    "test.js": "import test from 'ava';\nthrow new Error('source evidence must not execute');\ntest('releases a cancelled subscription', t => {});\n",
    "packages/worker/spec.mjs": "import test from 'node:test';\ntest('retains a completed operation', () => {});\n",
  });
  const inventory = await collectTestSuiteInventory(root);
  assert.equal(inventory.hasTestSuite, true);
  assert.equal(inventory.testFileCount, 2);
  assert.deepEqual(inventory.files.map(file => [file.path, file.testNames]), [
    ["packages/worker/spec.mjs", ["retains a completed operation"]],
    ["test.js", ["releases a cancelled subscription"]],
  ]);
});

test("canonical names do not turn similarly named source utilities into suite evidence", async () => {
  const root = await fixture(Object.fromEntries(["contest.js", "test-utils.js", "src/testing.js", "specifier.mjs"].map(file =>
    [file, "export function test(value) { return value; }\ntest('ordinary source value');\n"])));
  const inventory = await collectTestSuiteInventory(root);
  assert.equal(inventory.hasTestSuite, false);
  assert.equal(inventory.testFileCount, 0);
});

test("new contracts in canonical test and spec filenames retain their title and coordinates", () => {
  const evidence = Object.fromEntries(["test.js", "packages/tool/spec.mjs"].map(file => [file, [{
    file, startLine: 17, endLine: 17, hunkHeader: "@@ -0,0 +17 @@",
    lines: [{ line: 17, text: "test('retains a source contract', () => {});" }],
  }]]));
  assert.deepEqual(collectChangedTestContracts(evidence), [
    { file: "test.js", line: 17, framework: "javascript", title: "retains a source contract" },
    { file: "packages/tool/spec.mjs", line: 17, framework: "javascript", title: "retains a source contract" },
  ]);
});

test("repository metadata agrees with canonical and suffixed test filenames", async () => {
  const root = await fixture(Object.fromEntries(["test.js", "packages/tool/spec.mjs", "worker-test.cjs", "contest.js", "test-utils.js"].map(file =>
    [file, "export function example() {}\n"])));
  const index = await buildRepositoryEvidenceIndex(root, { cacheDirectory: false });
  assert.deepEqual(Object.fromEntries(index.blocks.map(block => [block.file, block.kind])), {
    "contest.js": "source", "packages/tool/spec.mjs": "test", "test-utils.js": "source", "test.js": "test", "worker-test.cjs": "test",
  });
});

test("generated canonical test output remains excluded from the suite inventory", async () => {
  const root = await fixture({ "test.js": "// Generated by QAMap\ntest('draft only', () => {});\n" });
  const inventory = await collectTestSuiteInventory(root);
  assert.equal(inventory.testFileCount, 0);
});

test("uncollected test filenames are a collection gap rather than proof that tests are absent", async () => {
  const root = await fixture({
    "checks.js": "import test from 'node:test';\ntest('an existing check outside naming patterns', () => {});\n",
  });
  const inventory = await collectTestSuiteInventory(root);
  assert.equal(inventory.hasTestSuite, false);
  assert.equal(await fs.readFile(path.join(root, "checks.js"), "utf8").then(text => text.includes("existing check")), true);
  const [evidence] = evaluateFlowCoverageEvidence({
    title: "Example flow", files: ["src/example.mjs"],
    coverage: [{ title: "Primary success path", checks: ["record an observable result"] }],
  }, inventory);
  assert.equal(evidence.status, "missing");
  assert.match(evidence.reason, /supported collection patterns/);
  assert.match(evidence.reason, /tests may exist outside that collection/);
  assert.doesNotMatch(evidence.reason, /No existing test files/);
});

test("a bootstrap collection gap asks for existing tests before proposing a new draft", async () => {
  const root = await fixture({
    "package.json": JSON.stringify({ type: "module", dependencies: { react: "^19.0.0" }, scripts: { test: "node --test checks.js" } }),
    "checks.js": "import test from 'node:test';\ntest('an existing check outside naming patterns', () => {});\n",
    "src/pages/Example.tsx": "export function Example() { return <button>Old value</button>; }\n",
  });
  const env = { ...process.env, GIT_CONFIG_GLOBAL: "/dev/null", GIT_CONFIG_NOSYSTEM: "1",
    GIT_AUTHOR_NAME: "Fixture", GIT_AUTHOR_EMAIL: "fixture@example.com",
    GIT_COMMITTER_NAME: "Fixture", GIT_COMMITTER_EMAIL: "fixture@example.com" };
  const git = (...args) => exec("git", args, { cwd: root, env });
  await git("init", "-q", "-b", "main");
  await git("add", "-A");
  await git("commit", "-q", "-m", "chore: baseline");
  await git("switch", "-q", "-c", "fix/example");
  await fs.writeFile(path.join(root, "src/pages/Example.tsx"), "export function Example() { return <button>Changed value</button>; }\n");
  await git("add", "-A");
  await git("commit", "-q", "-m", "fix: change the example label");
  const plan = await generateE2ePlan(root, { base: "main", head: "HEAD" });
  assert.equal(plan.testSuite.hasTestSuite, false);
  const draft = plan.bootstrap.steps.find(step => step.category === "draft");
  assert.equal(draft?.status, "required");
  assert.equal(draft.title, "Locate existing tests or create a changed-flow draft");
  assert.match(draft.reason, /Existing tests may be outside that collection/);
  assert.doesNotMatch(draft.reason, /No existing test files/);
});

test("canonical test files contribute binding-confirmed test references to a changed default export", async () => {
  const root = await fixture({
    "package.json": JSON.stringify({ type: "module", scripts: { test: "ava" } }),
    "src/measure.mjs": "export default function measure(value) {\n  return value;\n}\n",
    "test.js": "import test from 'ava';\nimport measure from './src/measure.mjs';\ntest('retains the measured value', t => {\n  t.is(measure(2), 2);\n});\n",
    "packages/tool/spec.mjs": "import test from 'node:test';\nimport assert from 'node:assert/strict';\nimport measure from '../../src/measure.mjs';\ntest('retains another measured value', () => {\n  assert.equal(measure(3), 3);\n});\n",
  });
  const env = { ...process.env, GIT_CONFIG_GLOBAL: "/dev/null", GIT_CONFIG_NOSYSTEM: "1",
    GIT_AUTHOR_NAME: "Fixture", GIT_AUTHOR_EMAIL: "fixture@example.com",
    GIT_COMMITTER_NAME: "Fixture", GIT_COMMITTER_EMAIL: "fixture@example.com", NO_COLOR: "1" };
  const git = (...args) => exec("git", args, { cwd: root, env });
  await git("init", "-q", "-b", "main");
  await git("add", "-A");
  await git("commit", "-q", "-m", "chore: baseline");
  await git("switch", "-q", "-c", "fix/measure");
  await fs.writeFile(path.join(root, "src/measure.mjs"), "export default function measure(value) {\n  return Math.max(0, value);\n}\n");
  await git("add", "-A");
  await git("commit", "-q", "-m", "fix: constrain measured values");
  const reportRoot = path.join(root, ".qamap", "reports");
  const { stdout } = await exec(process.execPath, [cli, "qa", "brief", ".", "--base", "main", "--output", reportRoot], { cwd: root, env });
  assert.match(stdout, /Changed declarations with collected test references: 1\/1/);
  assert.match(stdout, /test\.js:3 "retains the measured value"/);
  assert.match(stdout, /packages\/tool\/spec\.mjs:4 "retains another measured value"/);
  assert.doesNotMatch(stdout, /No collected test references: measure/);
  assert.match(stdout, /Static analysis only: no tests were run, no LLM was called\./);
});
