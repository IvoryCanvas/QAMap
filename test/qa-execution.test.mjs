test("qa run executes the exact selected repository test and returns bounded passing evidence", async () => {
  const root = await makeRepositoryTestFixture({
    testBody: `
import assert from "node:assert/strict";
import test from "node:test";

test("profile output stays visible", () => {
  console.log("PRIVATE_FIXTURE_OUTPUT_SHOULD_NOT_ENTER_THE_RECEIPT");
  assert.equal("Profile saved", "Profile saved");
});
`,
  });

  let streamedStdout = "";
  let streamedStderr = "";
  const result = await runQaValidation(root, {
    base: "main",
    head: "HEAD",
    onStdout: (chunk) => {
      streamedStdout += Buffer.from(chunk).toString("utf8");
    },
    onStderr: (chunk) => {
      streamedStderr += Buffer.from(chunk).toString("utf8");
    },
  });

  assert.equal(result.route.nextAction, "run-repository-command");
  assert.equal(result.execution.status, "passed");
  assert.equal(result.execution.performed, true);
  assert.equal(result.execution.scope, "repository-validation");
  assert.match(result.execution.command, /profile\.test\.mjs/);
  assert.equal(result.execution.exitCode, 0);
  assert.equal(result.execution.timedOut, false);
  assert.ok(result.execution.stdoutBytes > 0);
  assert.match(result.execution.stdoutSha256, /^[a-f0-9]{64}$/);
  assert.equal(result.execution.gitState.observed, true);
  assert.equal(result.execution.gitState.changed, false);
  assert.equal(result.execution.gitState.changedPathCount, 0);
  assert.deepEqual(result.execution.gitState.changedPaths, []);
  assert.equal(result.execution.gitState.headChanged, false);
  assert.equal(result.execution.gitState.branchChanged, false);
  assert.equal(
    result.execution.gitState.beforeSha256,
    result.execution.gitState.afterSha256,
  );
  assert.match(streamedStdout, /PRIVATE_FIXTURE_OUTPUT_SHOULD_NOT_ENTER_THE_RECEIPT/);
  assert.equal(result.execution.stderrBytes, Buffer.byteLength(streamedStderr, "utf8"));
  assert.doesNotMatch(streamedStderr, /PRIVATE_FIXTURE_OUTPUT_SHOULD_NOT_ENTER_THE_RECEIPT/);
  assert.doesNotMatch(
    JSON.stringify(result.execution),
    /PRIVATE_FIXTURE_OUTPUT_SHOULD_NOT_ENTER_THE_RECEIPT/,
  );

  const markdown = formatMarkdownQaValidation(result);
  assert.match(markdown, /# QAMap QA Run/);
  assert.match(markdown, /Status: passed/);
  assert.match(markdown, /Exit code: 0/);
  assert.match(markdown, /Output evidence: stdout/);
  assert.match(markdown, /Git-observable worktree changes: no/);
  assert.doesNotMatch(markdown, /PRIVATE_FIXTURE_OUTPUT_SHOULD_NOT_ENTER_THE_RECEIPT/);

  const agentOutput = formatAgentQaDraft(result);
  assert.ok(Buffer.byteLength(agentOutput, "utf8") <= 4_096);
  const agentResult = JSON.parse(agentOutput);
  assert.equal(agentResult.execution.status, "passed");
  assert.equal(agentResult.execution.command, result.execution.command);
  assert.doesNotMatch(agentOutput, /PRIVATE_FIXTURE_OUTPUT_SHOULD_NOT_ENTER_THE_RECEIPT/);
});

